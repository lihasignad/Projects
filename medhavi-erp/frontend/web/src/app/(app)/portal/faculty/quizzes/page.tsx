'use client';

import { useState } from 'react';
import Link from 'next/link';
import { MOCK_QUIZZES } from '@/features/portals/portals-mock-data';
import type { Quiz } from '@/features/portals/types';

/**
 * DESIGN BRIEF: Faculty Quiz Management & Question Bank Workbench
 * - Who uses: Faculty members creating chapter quizzes, setting deadlines, and monitoring class score distributions.
 * - Single most important thing: Fast question authoring with immediate feedback on correct options and passing criteria.
 * - Visual direction: Clean assessment workbench with responsive authoring form and class performance tables.
 * - Palette: Slate (`#0F172A`, `#334155`, `#F8FAFC`), Brand Ink (`#2563EB`), Emerald (`#059669`).
 * - Spacing & radius: 4px/8px grid, rounded-xl containers with subtle 1px border.
 */

export default function FacultyQuizManagerPage() {
  const [quizzes, setQuizzes] = useState<Quiz[]>(MOCK_QUIZZES);
  const [showCreateModal, setShowCreateModal] = useState(false);
  const [title, setTitle] = useState('');
  const [subjectCode, setSubjectCode] = useState('CS501');
  const [duration, setDuration] = useState(20);
  const [totalMarks, setTotalMarks] = useState(20);

  const handleCreateQuiz = (e: React.FormEvent) => {
    e.preventDefault();
    if (!title.trim()) return;

    const newQuiz: Quiz = {
      id: `quiz-cs-${Date.now()}`,
      title,
      subjectCode,
      subjectName: subjectCode === 'CS501' ? 'Database Management Systems' : 'Operating Systems',
      facultyName: 'Dr. Arvind Rao',
      batch: 'B.Tech CSE Sem 5 (Sec A)',
      durationMinutes: Number(duration),
      totalMarks: Number(totalMarks),
      passingMarks: Math.ceil(Number(totalMarks) * 0.4),
      deadline: '2026-11-08T18:00:00Z',
      status: 'active',
      questionsCount: 2,
      instructions: ['Timed assessment generated by Department of CSE.'],
      questions: [
        {
          id: 'new_q1',
          prompt: 'What constitutes a candidate key in relational database design?',
          options: [
            { id: 'opt1', text: 'Minimal superkey with unique identification' },
            { id: 'opt2', text: 'Any attribute containing foreign key references' },
            { id: 'opt3', text: 'Indexed columns with NULL allowance' },
            { id: 'opt4', text: 'Virtual generated column' },
          ],
          correctOptionId: 'opt1',
          explanation: 'A candidate key is defined as a minimal superkey capable of uniquely identifying every tuple.',
          points: 10,
        },
      ],
    };

    setQuizzes([newQuiz, ...quizzes]);
    setShowCreateModal(false);
    setTitle('');
    alert('New assessment published successfully to student portals!');
  };

  return (
    <div className="space-y-6">
      {/* Top Banner */}
      <div className="bg-white dark:bg-slate-900 border border-slate-200 dark:border-slate-800 rounded-xl p-5 shadow-sm">
        <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-4">
          <div>
            <div className="flex items-center space-x-2">
              <Link
                href="/portal/faculty"
                className="text-xs font-semibold text-brand-600 dark:text-brand-400 hover:underline"
              >
                Faculty Desk
              </Link>
              <span className="text-slate-300 dark:text-slate-700">|</span>
              <span className="text-xs text-slate-500">
                Department of Computer Science
              </span>
            </div>
            <h1 className="text-xl font-bold text-slate-900 dark:text-slate-100 mt-1">
              Quiz &amp; Question Bank Creator
            </h1>
            <p className="text-xs text-slate-500 dark:text-slate-400 mt-0.5">
              Design, publish, and evaluate internal chapter tests, mid-term evaluations, and surprise quizzes.
            </p>
          </div>

          <button
            type="button"
            onClick={() => setShowCreateModal(true)}
            className="px-4 py-2 rounded-lg bg-brand-600 hover:bg-brand-700 text-white text-xs font-semibold shadow-sm transition-colors self-start sm:self-auto focus-visible:outline-none focus-visible:ring-2 focus-visible:ring-brand-500 active:scale-[0.99]"
          >
            + Create New Assessment
          </button>
        </div>
      </div>

      {/* Quizzes Management Table */}
      <div className="bg-white dark:bg-slate-900 border border-slate-200 dark:border-slate-800 rounded-xl overflow-hidden shadow-sm">
        <div className="p-4 border-b border-slate-200 dark:border-slate-800 flex items-center justify-between">
          <h2 className="text-sm font-bold text-slate-900 dark:text-slate-100">
            Active &amp; Historical Department Assessments ({quizzes.length})
          </h2>
          <span className="text-xs font-mono text-slate-500">
            Auto-graded upon student submission
          </span>
        </div>

        <div className="overflow-x-auto">
          <table className="w-full text-left text-xs border-collapse">
            <thead>
              <tr className="bg-slate-50 dark:bg-slate-950 border-b border-slate-200 dark:border-slate-800 text-[11px] font-medium text-slate-500 font-semibold">
                <th className="px-4 py-3">Assessment Title</th>
                <th className="px-4 py-3">Course &amp; Batch</th>
                <th className="px-4 py-3 text-right">Duration</th>
                <th className="px-4 py-3 text-right">Marks</th>
                <th className="px-4 py-3 text-right">Questions</th>
                <th className="px-4 py-3 text-center">Status</th>
                <th className="px-4 py-3 text-right">Submissions / Class Performance</th>
              </tr>
            </thead>
            <tbody className="divide-y divide-slate-100 dark:divide-slate-800">
              {quizzes.map((quiz) => (
                <tr key={quiz.id} className="hover:bg-slate-50/50 dark:hover:bg-slate-800/40 transition-colors">
                  <td className="px-4 py-3 font-medium text-slate-900 dark:text-slate-100">
                    <div className="font-bold">{quiz.title}</div>
                    <div className="text-[11px] text-slate-500">Faculty: {quiz.facultyName}</div>
                  </td>
                  <td className="px-4 py-3">
                    <div className="font-mono font-bold text-brand-600 dark:text-brand-400">
                      {quiz.subjectCode}
                    </div>
                    <div className="text-slate-500 text-[11px]">{quiz.batch}</div>
                  </td>
                  <td className="px-4 py-3 text-right font-mono text-slate-700 dark:text-slate-300">
                    {quiz.durationMinutes} mins
                  </td>
                  <td className="px-4 py-3 text-right font-mono font-semibold text-slate-900 dark:text-slate-100">
                    {quiz.totalMarks}
                  </td>
                  <td className="px-4 py-3 text-right font-mono text-slate-700 dark:text-slate-300">
                    {quiz.questionsCount}
                  </td>
                  <td className="px-4 py-3 text-center">
                    <span
                      className={`px-2 py-0.5 rounded text-[10px] font-bold font-medium ${
                        quiz.status === 'active'
                          ? 'bg-rose-50 text-rose-700 dark:bg-rose-950 dark:text-rose-300 border border-rose-200 dark:border-rose-800 animate-pulse motion-reduce:animate-none'
                          : quiz.status === 'upcoming'
                          ? 'bg-amber-50 text-amber-700 dark:bg-amber-950 dark:text-amber-300 border border-amber-200 dark:border-amber-800'
                          : 'bg-emerald-50 text-emerald-700 dark:bg-emerald-950 dark:text-emerald-300 border border-emerald-200 dark:border-emerald-800'
                      }`}
                    >
                      {quiz.status}
                    </span>
                  </td>
                  <td className="px-4 py-3 text-right">
                    <div className="text-xs font-semibold text-slate-900 dark:text-slate-100">
                      {quiz.status === 'completed' ? '64 / 64 Submitted (Avg 86%)' : '48 / 64 Submitted'}
                    </div>
                    <button
                      type="button"
                      onClick={() => alert(`Reviewing all student scorecards for ${quiz.title}`)}
                      className="text-brand-600 dark:text-brand-400 font-semibold hover:underline text-[11px]"
                    >
                      Inspect Scores
                    </button>
                  </td>
                </tr>
              ))}
            </tbody>
          </table>
        </div>
      </div>

      {/* Create Modal */}
      {showCreateModal && (
        <div className="fixed inset-0 z-50 flex items-center justify-center p-4 bg-slate-900/60 backdrop-blur-sm">
          <div className="bg-white dark:bg-slate-900 rounded-xl max-w-lg w-full p-6 shadow-xl border border-slate-200 dark:border-slate-800 space-y-4">
            <h3 className="text-base font-bold text-slate-900 dark:text-slate-100">
              Create New Assessment
            </h3>
            <form onSubmit={handleCreateQuiz} className="space-y-4 text-xs">
              <div>
                <label className="block font-medium text-slate-700 dark:text-slate-300 mb-1">
                  Assessment Title
                </label>
                <input
                  type="text"
                  required
                  placeholder="e.g. Unit 3 Quiz: Indexing & Query Optimization"
                  value={title}
                  onChange={(e) => setTitle(e.target.value)}
                  className="w-full p-2.5 rounded-lg border border-slate-200 dark:border-slate-700 bg-white dark:bg-slate-900 text-slate-900 dark:text-slate-100"
                />
              </div>

              <div className="grid grid-cols-3 gap-3">
                <div>
                  <label className="block font-medium text-slate-700 dark:text-slate-300 mb-1">
                    Subject
                  </label>
                  <select
                    value={subjectCode}
                    onChange={(e) => setSubjectCode(e.target.value)}
                    className="w-full p-2.5 rounded-lg border border-slate-200 dark:border-slate-700 bg-white dark:bg-slate-900 font-mono"
                  >
                    <option value="CS501">CS501 DBMS</option>
                    <option value="CS502">CS502 OS</option>
                    <option value="CS702">CS702 Cloud</option>
                  </select>
                </div>
                <div>
                  <label className="block font-medium text-slate-700 dark:text-slate-300 mb-1">
                    Duration (mins)
                  </label>
                  <input
                    type="number"
                    min="5"
                    max="180"
                    value={duration}
                    onChange={(e) => setDuration(Number(e.target.value))}
                    className="w-full p-2.5 rounded-lg border border-slate-200 dark:border-slate-700 bg-white dark:bg-slate-900 font-mono"
                  />
                </div>
                <div>
                  <label className="block font-medium text-slate-700 dark:text-slate-300 mb-1">
                    Total Marks
                  </label>
                  <input
                    type="number"
                    min="5"
                    max="100"
                    value={totalMarks}
                    onChange={(e) => setTotalMarks(Number(e.target.value))}
                    className="w-full p-2.5 rounded-lg border border-slate-200 dark:border-slate-700 bg-white dark:bg-slate-900 font-mono"
                  />
                </div>
              </div>

              <div className="p-3 rounded-lg bg-slate-50 dark:bg-slate-950 border border-slate-200 dark:border-slate-800 text-slate-600 dark:text-slate-400 text-[11px]">
                Questions will be populated from the certified Department of CSE Question Bank and immediately activated for registered students in Section A.
              </div>

              <div className="flex justify-end space-x-3 pt-2">
                <button
                  type="button"
                  onClick={() => setShowCreateModal(false)}
                  className="px-4 py-2 rounded-lg border border-slate-200 dark:border-slate-700 text-slate-700 dark:text-slate-300 hover:bg-slate-50 focus-visible:outline-none focus-visible:ring-2 focus-visible:ring-brand-500 active:scale-[0.99]"
                >
                  Cancel
                </button>
                <button
                  type="submit"
                  className="px-4 py-2 rounded-lg bg-brand-600 hover:bg-brand-700 text-white font-semibold focus-visible:outline-none focus-visible:ring-2 focus-visible:ring-brand-500 active:scale-[0.99]"
                >
                  Publish Assessment
                </button>
              </div>
            </form>
          </div>
        </div>
      )}
    </div>
  );
}
